/** Слово для счётчика: «упаковок» / «ампул» / … */
export function unitWord(form, n) {
  const table = {
    'ампулы': ['ампула', 'ампулы', 'ампул'],
    'пакетики': ['пакетик', 'пакетика', 'пакетиков'],
    'свечи': ['свеча', 'свечи', 'свечей'],
    'шипучие таблетки': ['таблетка', 'таблетки', 'таблеток'],
    'пластырь': ['пластырь', 'пластыря', 'пластырей'],
    'порошок': ['пакетик', 'пакетика', 'пакетиков'],
    'флакон': ['флакон', 'флакона', 'флаконов'],
  }
  const forms = table[form] || ['упаковка', 'упаковки', 'упаковок']
  return plural(n, forms)
}

export function plural(n, [one, few, many]) {
  const a = Math.abs(n) % 100
  const b = a % 10
  if (a > 10 && a < 20) return many
  if (b > 1 && b < 5) return few
  if (b === 1) return one
  return many
}
